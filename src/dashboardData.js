export function formatNumber(value) {
  return Math.abs(value).toLocaleString("en-US");
}

export function formatSigned(value) {
  const sign = value > 0 ? "+" : value < 0 ? "-" : "";
  return `${sign}${formatNumber(value)}`;
}

